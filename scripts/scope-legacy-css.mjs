// Scopes the original NOVATECH IRM global stylesheet (src/styles.css) under `.ent-root`, so the original
// enterprise pages can live inside the Sentinel shell without changing Sentinel's own pages.
//   :root / :root[data-theme='dark']  → .ent-root
//   :root[data-theme='light'] X       → :root[data-theme='light'] .ent-root X
//   html, body, #root                 → .ent-root
//   any other selector X              → .ent-root X
// Run: node scripts/scope-legacy-css.mjs   (writes src/enterprise/ui/legacy-scoped.css)
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const SCOPE = '.ent-root';
const src = readFileSync(new URL('../src/styles.css', import.meta.url), 'utf8');

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  if (/^(html|body|#root)$/.test(s)) return SCOPE;
  if (s === ':root' || s === ":root[data-theme='dark']" || s === ':root[data-theme="dark"]') return SCOPE;
  const light = s.match(/^:root\[data-theme=['"]light['"]\]\s*(.*)$/);
  if (light) return light[1] ? `:root[data-theme='light'] ${SCOPE} ${light[1]}` : `:root[data-theme='light'] ${SCOPE}`;
  const dark = s.match(/^:root\[data-theme=['"]dark['"]\]\s+(.*)$/);
  if (dark) return `:root[data-theme='dark'] ${SCOPE} ${dark[1]}`;
  if (s.startsWith(':root ')) return `${SCOPE} ${s.slice(6)}`;
  if (/^(html|body)\s/.test(s)) return `${SCOPE} ${s.replace(/^(html|body)\s+/, '')}`;
  if (s === '*' || s.startsWith('*')) return `${SCOPE} ${s}`;
  return `${SCOPE} ${s}`;
}

const plugin = () => ({
  postcssPlugin: 'scope-legacy',
  Rule(rule) {
    if (rule.__scoped) return;
    const parent = rule.parent;
    if (parent && parent.type === 'atrule' && /keyframes$/i.test(parent.name)) return;
    rule.selectors = rule.selectors.map(scopeSelector);
    rule.__scoped = true;
  },
});
plugin.postcss = true;

const out = await postcss([plugin]).process(src, { from: undefined });
const header = `/* GENERATED by scripts/scope-legacy-css.mjs from src/styles.css — do not edit by hand. */\n`;
writeFileSync(new URL('../src/enterprise/ui/legacy-scoped.css', import.meta.url), header + out.css);
console.log('Wrote src/enterprise/ui/legacy-scoped.css', out.css.length, 'bytes');
